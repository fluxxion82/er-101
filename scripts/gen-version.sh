#!/bin/sh
# Write version.h from FIRMWARE_VERSION (scripts/env.mk), the one place the version lives.
#   sh scripts/gen-version.sh 3.0.0 build/generated/version.h
# MAJOR and PATCH must be one digit and MINOR at most two: the boot splash shows
# "F<major>." over "<minor>" and "P<patch>" on 7-segment displays (src/display.c).
set -eu
version=$1
out=$2
case $version in
  [0-9].[0-9].[0-9]|[0-9].[0-9][0-9].[0-9]) ;;
  *) echo "gen-version: '$version' is not MAJOR.MINOR.PATCH with one-digit MAJOR and PATCH and MINOR under 100" >&2; exit 1 ;;
esac
major=${version%%.*}
rest=${version#*.}
minor=${rest%%.*}
patch=${rest#*.}
mkdir -p "$(dirname "$out")"
tmp=$out.tmp
{
  echo "/* Generated by scripts/gen-version.sh from FIRMWARE_VERSION in scripts/env.mk. Do not edit. */"
  echo "#ifndef VERSION_H_"
  echo "#define VERSION_H_"
  echo "#define FIRMWARE_VERSION_STRING \"$version\""
  echo "#define FIRMWARE_VERSION_MAJOR $major"
  echo "#define FIRMWARE_VERSION_MINOR $minor"
  echo "#define FIRMWARE_VERSION_PATCH $patch"
  echo "#endif /* VERSION_H_ */"
} > "$tmp"
# Only touch the header when it changes, so nothing rebuilds needlessly.
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then rm -f "$tmp"; else mv "$tmp" "$out"; fi
